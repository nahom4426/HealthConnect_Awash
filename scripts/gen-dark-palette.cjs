#!/usr/bin/env node
// Writes dark-mode equivalents for the light Tailwind palette utilities used in src/ (bg-emerald-50,
// border-amber-200, text-blue-900, hover:bg-gray-50, bg-white/80 …) into the generated block of
// src/assets/theme-dark.css. Hand-written rules above the block win, so only missing classes are
// added. Strong fills (bg-blue-600, text-white on buttons) look right in both themes and are left.
// Run again after adding new palette classes: node scripts/gen-dark-palette.cjs
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CSS = path.join(ROOT, "src/assets/theme-dark.css");
const BEGIN = "/* ── generated by scripts/gen-dark-palette.cjs — do not edit below ── */";
const END = "/* ── end generated ── */";

// Tailwind v3 palette: the 400 and 500 shades as "r g b"
const P = {
  gray: ["156 163 175", "107 114 128"], slate: ["148 163 184", "100 116 139"], zinc: ["161 161 170", "113 113 122"],
  neutral: ["163 163 163", "115 115 115"], stone: ["168 162 158", "120 113 108"],
  red: ["248 113 113", "239 68 68"], orange: ["251 146 60", "249 115 22"], amber: ["251 191 36", "245 158 11"],
  yellow: ["250 204 21", "234 179 8"], lime: ["163 230 53", "132 204 22"], green: ["74 222 128", "34 197 94"],
  emerald: ["52 211 153", "16 185 129"], teal: ["45 212 191", "20 184 166"], cyan: ["34 211 238", "6 182 212"],
  sky: ["56 189 248", "14 165 233"], blue: ["96 165 250", "59 130 246"], indigo: ["129 140 248", "99 102 241"],
  violet: ["167 139 250", "139 92 246"], purple: ["192 132 252", "168 85 247"], fuchsia: ["232 121 249", "217 70 239"],
  pink: ["244 114 182", "236 72 153"], rose: ["251 113 133", "244 63 94"],
};
const GREYS = new Set(["gray", "slate", "zinc", "neutral", "stone"]);
const VARIANTS = { "": "", "hover:": ":hover", "focus:": ":focus", "focus-within:": ":focus-within", "active:": ":active" };

/** Dark declaration for one base utility, or null when it already works in dark mode. */
function darkRule(util) {
  let m = util.match(/^bg-white(?:\/(\d+))?$/);
  if (m) return `background-color: rgb(var(--surface)${m[1] ? ` / ${Number(m[1]) / 100}` : ""})`;
  m = util.match(/^(bg|border|text|divide|ring|placeholder|from|via|to)-([a-z]+)-(\d{2,3})(?:\/(\d+))?$/);
  if (!m) return null;
  const [, kind, color, shadeS, alphaS] = m;
  if (!P[color]) return null;
  const shade = Number(shadeS);
  const [c400, c500] = P[color];
  const grey = GREYS.has(color);
  if (kind === "bg") {
    if (shade > 300) return null; // strong fills read fine on dark
    if (grey) return `background-color: rgb(var(${shade <= 100 ? "--surface-muted" : "--surface-raised"}))`;
    const a = { 50: 0.1, 100: 0.14, 200: 0.2, 300: 0.28 }[shade] ?? 0.14;
    return `background-color: rgb(${c500} / ${alphaS ? Math.round((Number(alphaS) / 100) * a * 200) / 100 : a})`;
  }
  if (kind === "border" || kind === "divide" || kind === "ring") {
    if (shade > 400) return null;
    const prop = kind === "border" ? "border-color" : kind === "divide" ? "border-color" : "--tw-ring-color";
    if (grey) return `${prop}: rgb(var(${shade <= 200 ? "--line" : "--line-strong"}))`;
    return `${prop}: rgb(${c500} / ${shade <= 100 ? 0.22 : shade <= 200 ? 0.3 : 0.42})`;
  }
  if (kind === "text") {
    if (shade < 600) return null; // light/mid text is readable on dark
    if (grey) return `color: rgb(var(${shade >= 800 ? "--ink" : "--ink-muted"}))`;
    return `color: rgb(${c400})`;
  }
  if (kind === "placeholder") return grey ? "color: rgb(var(--ink-subtle))" : null;
  if (kind === "from" || kind === "via" || kind === "to") {
    if (shade > 200) return null;
    const v = kind === "from" ? "--tw-gradient-from" : kind === "to" ? "--tw-gradient-to" : "--tw-gradient-via";
    return `${v}: rgb(${c500} / 0.14) var(--tw-gradient-${kind}-position)`;
  }
  return null;
}

const esc = (s) => s.replace(/[:/]/g, (c) => `\\${c}`);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(vue|js|ts)$/.test(e.name)) out.push(p);
  }
  return out;
}

const css = fs.readFileSync(CSS, "utf8");
const head = css.includes(BEGIN) ? css.slice(0, css.indexOf(BEGIN)) : css.trimEnd() + "\n\n";
const handWritten = new Set([...head.matchAll(/\[data-theme="dark"\]\s+\.([^\s{:]+(?:\\:[^\s{]+)?)/g)].map((m) => m[1].replace(/\\/g, "")));

const used = new Set();
const re = /(?<![\w-])((?:hover:|focus:|focus-within:|active:|group-hover:)?(?:bg-white(?:\/\d+)?|(?:bg|border|text|divide|ring|placeholder|from|via|to)-[a-z]+-\d{2,3}(?:\/\d+)?))(?![\w-])/g;
for (const f of walk(path.join(ROOT, "src"))) {
  for (const m of fs.readFileSync(f, "utf8").matchAll(re)) used.add(m[1]);
}

const rules = [];
for (const cls of [...used].sort()) {
  const vm = cls.match(/^(hover:|focus:|focus-within:|active:|group-hover:)?(.*)$/);
  const variant = vm[1] || "";
  const base = vm[2];
  if (!variant && handWritten.has(base)) continue;
  const decl = darkRule(base);
  if (!decl) continue;
  const selector = variant === "group-hover:"
    ? `[data-theme="dark"] .group:hover .${esc(cls)}`
    : `[data-theme="dark"] .${esc(cls)}${VARIANTS[variant]}`;
  rules.push(`${selector} { ${decl}; }`);
}

fs.writeFileSync(CSS, `${head}${BEGIN}\n${rules.join("\n")}\n${END}\n`);
console.log(`dark palette: ${rules.length} generated rules (${used.size} palette classes in use)`);
